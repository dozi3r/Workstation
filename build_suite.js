function parseYamlListOrArray(val) {
  if (!val) return [];
  if (Array.isArray(val)) return val;
  const str = String(val).trim();
  if (str.startsWith('[') && str.endsWith(']')) {
    try {
      return JSON.parse(str);
    } catch(e) {
      return str.slice(1, -1).split(',').map(s => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
    }
  }
  return str.split('\n').map(l => l.replace(/^[-*]\s*/, '').trim().replace(/^["']|["']$/g, '')).filter(Boolean);
}

function scanModulesDirRecursive(modulesRootDir, campaignRootDir, deletedIdsSet = new Set()) {
  const discovered = [];
  if (!fs.existsSync(modulesRootDir)) return discovered;

  function walk(currentDir) {
    const entries = fs.readdirSync(currentDir, { withFileTypes: true });
    for (const ent of entries) {
      const fullPath = path.join(currentDir, ent.name);
      if (ent.isDirectory() && !ent.name.startsWith('.') && !ent.name.startsWith('_')) {
        walk(fullPath);
      } else if (ent.isFile() && ent.name.toLowerCase().endsWith('.md') && !ent.name.toLowerCase().startsWith('readme')) {
        try {
          const rawText = fs.readFileSync(fullPath, 'utf8');
          let fm = {};
          const fmMatch = rawText.match(/^---\r?\n([\s\S]*?)\r?\n---/);
          if (fmMatch) {
            const fmLines = fmMatch[1].split('\n');
            let currentKey = null;
            let currentList = null;

            for (let line of fmLines) {
              const trimmed = line.trim();
              if (!trimmed || trimmed.startsWith('#')) continue;

              const kvMatch = line.match(/^([a-zA-Z0-9_-]+)\s*:\s*(.*)$/);
              if (kvMatch && !line.startsWith(' ') && !line.startsWith('\t')) {
                currentKey = kvMatch[1].trim();
                let rawVal = kvMatch[2].trim();
                if (rawVal.startsWith('[') && rawVal.endsWith(']')) {
                  fm[currentKey] = parseYamlListOrArray(rawVal);
                  currentList = null;
                } else if (rawVal === '') {
                  currentList = [];
                  fm[currentKey] = currentList;
                } else {
                  fm[currentKey] = rawVal.replace(/^["']|["']$/g, '');
                  currentList = null;
                }
              } else if (currentList && (line.startsWith('  -') || line.startsWith('  *') || line.startsWith(' -') || line.startsWith('-'))) {
                currentList.push(trimmed.replace(/^[-*]\s*/, '').replace(/^["']|["']$/g, '').trim());
              }
            }
          }

          let modId = fm.id || fm.module_id;
          if (!modId) {
            const baseNoExt = path.basename(ent.name, '.md');
            const prefixMatch = baseNoExt.match(/^([A-Z0-9]+-[0-9]+|[A-Z0-9]+)/i);
            modId = prefixMatch ? prefixMatch[1] : baseNoExt;
          }

          if (deletedIdsSet.has(String(modId))) {
            continue;
          }

          let title = fm.title;
          if (!title) {
            const h1Match = rawText.match(/^#\s+(?:MODULE\s+[A-Z0-9-]+:\s*)?([^\r\n]+)/m);
            title = h1Match ? h1Match[1].trim() : path.basename(ent.name, '.md').replace(/_/g, ' ');
          }

          const pipelineTier = fm.pipeline_tier ? parseInt(fm.pipeline_tier) : (fm.tier && fm.tier.match(/Tier\s*(\d)/i) ? parseInt(fm.tier.match(/Tier\s*(\d)/i)[1]) : 3);
          const relPath = './' + path.relative(campaignRootDir, fullPath).replace(/\\/g, '/');

          // Detect set name from folder
          let setName = fm.set;
          if (!setName) {
            const parentFolderName = path.basename(path.dirname(fullPath));
            if (parentFolderName.startsWith('Set_')) {
              setName = parentFolderName.replace(/_/g, ' ');
            } else {
              setName = "Core Modules";
            }
          }

          discovered.push({
            id: String(modId),
            title: title,
            set: setName,
            tier: fm.tier || `Tier ${pipelineTier}`,
            pipeline_tier: pipelineTier,
            culture: fm.culture || fm.culture_quadrant || "Universal",
            color: fm.color || fm.mtg_color || "Colorless",
            provides: parseYamlListOrArray(fm.provides),
            requires: parseYamlListOrArray(fm.requires),
            summary: fm.summary || fm.yields || fm.description || "",
            yields: fm.yields_resource || fm.yields || "",
            path: relPath,
            standalone_fallback: fm.standalone_fallback || ""
          });
        } catch(readErr) {
          console.warn(`[WARN] Could not parse module at ${fullPath}:`, readErr.message);
        }
      }
    }
  }

  walk(modulesRootDir);
  return discovered;
}

