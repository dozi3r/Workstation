function resolveNodeOdv(node, fallbackIndex) {
  if (!node) return { s: 2, e: 2, c: 2, tag: "[2, 2, 2]", explicit: false };
  let s = 2, e = 2, c = 2;
  let explicit = false;
  const raw = node.odv !== undefined ? node.odv : node.disposition;

  if (raw) {
    if (Array.isArray(raw) && raw.length >= 3) {
      s = parseInt(raw[0], 10) || 2;
      e = parseInt(raw[1], 10) || 2;
      c = parseInt(raw[2], 10) || 2;
      explicit = true;
    } else if (typeof raw === "object" && (raw.s !== undefined || raw.e !== undefined || raw.c !== undefined)) {
      s = parseInt(raw.s !== undefined ? raw.s : raw[0], 10) || 2;
      e = parseInt(raw.e !== undefined ? raw.e : raw[1], 10) || 2;
      c = parseInt(raw.c !== undefined ? raw.c : raw[2], 10) || 2;
      explicit = true;
    } else if (typeof raw === "string") {
      const m = raw.match(/(\d+)\D+(\d+)\D+(\d+)/);
      if (m) {
        s = parseInt(m[1], 10) || 2;
        e = parseInt(m[2], 10) || 2;
        c = parseInt(m[3], 10) || 2;
        explicit = true;
      }
    }
  }

  if (!explicit) {
    // 1. Mod Hook: Check for registered custom ODV fallback resolver (e.g. Tarot Mod)
    let resolvedByMod = false;
    if (typeof window !== "undefined" && window.CreatorStudio && typeof window.CreatorStudio.customOdvFallbackResolver === "function") {
      try {
        const modRes = window.CreatorStudio.customOdvFallbackResolver(node, fallbackIndex);
        if (modRes && modRes.s !== undefined) {
          s = modRes.s; e = modRes.e; c = modRes.c;
          resolvedByMod = true;
        }
      } catch(_) {}
    }

    // 2. Canonical Mathematical Baseline: Respect CVF quadrant culture, or neutral [2, 2, 2] ("The Deliberative Concord")
    if (!resolvedByMod) {
      if (node && node.culture) {
        if (node.culture === "Clan")           { s = 3; e = 2; c = 2; }
        else if (node.culture === "Adhocracy") { s = 3; e = 3; c = 3; }
        else if (node.culture === "Market")    { s = 2; e = 3; c = 2; }
        else if (node.culture === "Hierarchy") { s = 2; e = 2; c = 2; }
        else                                   { s = 2; e = 2; c = 2; }
      } else {
        s = 2; e = 2; c = 2;
      }
    }
  }

  s = Math.max(1, Math.min(4, s));
  e = Math.max(1, Math.min(4, e));
  c = Math.max(1, Math.min(4, c));
  return { s, e, c, tag: `[${s}, ${e}, ${c}]`, explicit };
}

function resolveEdgeOdv(edge, uNodeOdv, vNodeOdv, edgeRecord) {
  const u = uNodeOdv || { s: 2, e: 2, c: 2 };
  const v = vNodeOdv || { s: 2, e: 2, c: 2 };
  const raw = (edge && (edge.odv || edge.disposition)) || (edgeRecord && (edgeRecord.odv || edgeRecord.disposition));

  let s, e, c;
  let explicit = false;
  if (raw) {
    if (Array.isArray(raw) && raw.length >= 3) {
      s = parseInt(raw[0], 10) || 2;
      e = parseInt(raw[1], 10) || 2;
      c = parseInt(raw[2], 10) || 2;
      explicit = true;
    } else if (typeof raw === "object" && (raw.s !== undefined || raw.e !== undefined || raw.c !== undefined)) {
      s = parseInt(raw.s !== undefined ? raw.s : raw[0], 10) || 2;
      e = parseInt(raw.e !== undefined ? raw.e : raw[1], 10) || 2;
      c = parseInt(raw.c !== undefined ? raw.c : raw[2], 10) || 2;
      explicit = true;
    }
  }

  if (!explicit) {
    s = Math.round((u.s + v.s) / 2);
    e = Math.round((u.e + v.e) / 2);
    c = Math.round((u.c + v.c) / 2);
  }

  s = Math.max(1, Math.min(4, s));
  e = Math.max(1, Math.min(4, e));
  c = Math.max(1, Math.min(4, c));
  const totalDelta = Math.abs(u.s - v.s) + Math.abs(u.e - v.e) + Math.abs(u.c - v.c);

  return {
    s, e, c,
    tag: `[${s}, ${e}, ${c}]`,
    explicit,
    totalDelta,
    isHighHazard: totalDelta >= 5
  };
}

function buildCampaignOdvIndex(topology) {
  const index = {};
  for (let s = 1; s <= 4; s++) {
    for (let e = 1; e <= 4; e++) {
      for (let c = 1; c <= 4; c++) {
        index[`[${s}, ${e}, ${c}]`] = { nodes: [], edges: [] };
      }
    }
  }

  if (!topology) return index;

  let targetTopo = topology;
  if (!targetTopo.nodes && targetTopo.maps) {
    const rootKey = targetTopo.activeMapId || targetTopo.rootMapId || "map_root";
    targetTopo = targetTopo.maps[rootKey] || Object.values(targetTopo.maps)[0] || topology;
  }

  const rawNodes = targetTopo.nodes || {};
  const nodeList = Array.isArray(rawNodes)
    ? rawNodes
    : Object.entries(rawNodes).map(([k, v]) => ({ id: v.id !== undefined ? v.id : (isNaN(Number(k)) ? k : Number(k)), ...v }));

  const nodeById = {};
  const nodeOdvById = {};

  nodeList.forEach((n, idx) => {
    if (!n) return;
    const nid = n.id !== undefined ? n.id : (idx + 1);
    const resolved = resolveNodeOdv({ ...n, id: nid }, idx + 1);
    const nodeEntry = {
      id: nid,
      name: n.displayName || n.name || n.label || `Node ${nid}`,
      cat: n.cat || n.type || "Settlement",
      culture: n.culture || deriveCvfQuadrant(resolved.s, resolved.e),
      tier: n.tier || n.wave || 1,
      s: resolved.s,
      e: resolved.e,
      c: resolved.c,
      tag: resolved.tag,
      explicit: resolved.explicit
    };
    nodeById[String(nid)] = nodeEntry;
    nodeOdvById[String(nid)] = resolved;
    if (index[resolved.tag]) {
      index[resolved.tag].nodes.push(nodeEntry);
    }
  });

  const edgeDataDict = targetTopo.edgeData || topology.edgeData || {};
  const seenRoadPairs = new Set();
  const rawLinks = Array.isArray(targetTopo.links) ? targetTopo.links : [];

  function registerCorridor(uId, vId, linkObj, isDirected) {
    const uKey = String(uId);
    const vKey = String(vId);
    if (uKey === vKey) return;
    const pairKey = isDirected ? `${uKey}->${vKey}` : [uKey, vKey].sort((a, b) => (Number(a) - Number(b)) || a.localeCompare(b)).join("-");
    if (seenRoadPairs.has(pairKey)) return;
    seenRoadPairs.add(pairKey);

    const edgeRecord = edgeDataDict[pairKey] || edgeDataDict[`${uKey}-${vKey}`] || edgeDataDict[`${vKey}-${uKey}`] || null;
    const uNode = nodeById[uKey] || { id: uId, name: (linkObj && linkObj.fromName) || `Node ${uId}` };
    const vNode = nodeById[vKey] || { id: vId, name: (linkObj && linkObj.toName) || `Node ${vId}` };
    const resolved = resolveEdgeOdv(linkObj, nodeOdvById[uKey], nodeOdvById[vKey], edgeRecord);

    const customName = (edgeRecord && edgeRecord.name) || (linkObj && linkObj.name) || `${uNode.name} ↔ ${vNode.name}`;
    const condition = (edgeRecord && edgeRecord.condition) || (linkObj && linkObj.condition) || "Passable";

    const edgeEntry = {
      key: pairKey,
      uId: uNode.id,
      vId: vNode.id,
      uName: uNode.name,
      vName: vNode.name,
      name: customName,
      condition,
      isDirected: !!isDirected,
      s: resolved.s,
      e: resolved.e,
      c: resolved.c,
      tag: resolved.tag,
      explicit: resolved.explicit,
      totalDelta: resolved.totalDelta,
      isHighHazard: resolved.isHighHazard
    };

    if (index[resolved.tag]) {
      index[resolved.tag].edges.push(edgeEntry);
    }
  }

  nodeList.forEach(n => {
    if (Array.isArray(n.adj)) {
      n.adj.forEach(neighborId => {
        registerCorridor(n.id, neighborId, null, false);
      });
    }
  });

  rawLinks.forEach(l => {
    if (l && l.from !== undefined && l.to !== undefined) {
      const isDirected = (l.type === "oneway" || l.layer === "hegemony");
      registerCorridor(l.from, l.to, l, isDirected);
    }
  });

  return index;
}

